import { ChatOpenAI } from '@langchain/openai';

/**
 * Synthesizer Node — Node 4 (final) of the LangGraph pipeline.
 *
 * Aggregates all research + analysis into a structured final report with:
 * - INVEST or PASS recommendation
 * - Confidence level
 * - Executive summary
 * - Bull case (3 reasons to invest)
 * - Bear case (3 reasons to avoid)
 * - Standard financial disclaimer
 *
 * @param {import('../state.js').AgentState} state
 * @param {Object} options
 * @param {Function} options.emit - SSE event emitter
 * @returns {Partial<import('../state.js').AgentState>}
 */
export async function synthesizerNode(state, { emit }) {
  emit('stage', {
    stage: 'synthesizing',
    message: '✍️ Writing investment recommendation report...',
  });

  const llm = new ChatOpenAI({
    model: 'gpt-4o',
    temperature: 0.2,
    maxRetries: 2,
    apiKey: process.env.OPENAI_API_KEY,
  });

  const { analysis, riskAssessment } = state;
  const researchContext = state.researchResults
    .map((r) => `### ${r.topic}\n${r.summary}`)
    .join('\n\n');

  // Build risk context from dedicated riskAssessor node
  const riskContext = riskAssessment
    ? `RISK ASSESSMENT (from dedicated risk analysis):
- Overall Risk Level: ${riskAssessment.overallRiskLevel}
- Risk Score: ${riskAssessment.riskScore}/10
- Risk Summary: ${riskAssessment.riskSummary}
- Top Risks: ${riskAssessment.topRisks?.map((r) => `${r.title} (${r.severity})`).join(', ')}
- Red Flags: ${riskAssessment.redFlags?.length > 0 ? riskAssessment.redFlags.join('; ') : 'None identified'}
- Positive Factors: ${riskAssessment.positiveFactors?.join('; ')}`
    : '';

  // Decision logic: overall score + risk (use riskAssessor's level if available)
  const score = analysis?.overallScore || 5;
  const riskLevel = riskAssessment?.overallRiskLevel || analysis?.riskLevel || 'Medium';

  // Preliminary recommendation to guide the LLM
  let preliminaryRec = 'PASS';
  if (score >= 7.0 && riskLevel !== 'High') {
    preliminaryRec = 'INVEST';
  } else if (score >= 6.0 && riskLevel === 'Low') {
    preliminaryRec = 'INVEST';
  }

  const prompt = `You are a senior partner at a leading investment firm writing a final investment memo for "${state.companyName}".

QUANTITATIVE SCORES:
- Financial Health: ${analysis?.financialHealth}/10 — ${analysis?.financialHealthReasoning}
- Competitive Moat: ${analysis?.competitiveMoat}/10 — ${analysis?.competitiveMoatReasoning}
- Growth Potential: ${analysis?.growthPotential}/10 — ${analysis?.growthPotentialReasoning}
- Risk Level: ${riskLevel} — ${analysis?.riskLevelReasoning}
- Overall Score: ${score}/10

${riskContext}

RESEARCH FINDINGS:
${researchContext}

Based on this analysis (preliminary recommendation: ${preliminaryRec}), write a comprehensive investment memo as a JSON object with EXACTLY this structure:
{
  "recommendation": "${preliminaryRec}",
  "confidence": "<High|Medium|Low>",
  "executiveSummary": "<3-4 paragraph executive summary covering business overview, financial analysis, competitive position, risk profile, and your final verdict. Be specific with numbers and facts.>",
  "bullCase": [
    "<Specific, compelling reason 1 to invest with supporting data>",
    "<Specific, compelling reason 2 to invest with supporting data>",
    "<Specific, compelling reason 3 to invest with supporting data>"
  ],
  "bearCase": [
    "<Specific risk 1 drawn from the risk assessment, with evidence>",
    "<Specific risk 2 drawn from the risk assessment, with evidence>",
    "<Specific risk 3 drawn from the risk assessment, with evidence>"
  ],
  "keyMetrics": "<2-3 sentence summary of the most important financial metrics found>",
  "disclaimer": "This analysis is generated by an AI research agent for informational purposes only and does not constitute financial advice. Always conduct your own due diligence before making investment decisions."
}

Confidence guidance: High=strong data with clear signals, Medium=mixed signals or some data gaps, Low=limited data or very uncertain outlook.
The bearCase MUST reflect the specific risks identified in the RISK ASSESSMENT section above.
Return ONLY the JSON object.`;

  const response = await llm.invoke([{ role: 'user', content: prompt }]);
  const content = response.content.trim();

  let finalReport;
  try {
    const match = content.match(/\{[\s\S]*\}/);
    finalReport = JSON.parse(match ? match[0] : content);
  } catch {
    finalReport = {
      recommendation: preliminaryRec,
      confidence: 'Low',
      executiveSummary: `Analysis of ${state.companyName} based on available research data. Score: ${score}/10.`,
      bullCase: ['Strong market position', 'Growth potential identified', 'Established brand'],
      bearCase: ['Market uncertainty', 'Competitive pressures', 'Execution risk'],
      keyMetrics: 'Detailed financial metrics require additional research.',
      disclaimer:
        'This analysis is for informational purposes only and does not constitute financial advice.',
    };
  }

  // Gather all unique sources (research + risk assessment)
  const allSources = [
    ...state.researchResults.flatMap((r) => r.sources || []),
    ...(state.riskAssessment?.sources || []),
  ]
    .filter((s, i, arr) => s.url && arr.findIndex((x) => x.url === s.url) === i)
    .slice(0, 12);

  finalReport.sources = allSources;
  finalReport.riskAssessment = state.riskAssessment;

  emit('stage', {
    stage: 'complete',
    message: `🎯 Research complete — ${finalReport.recommendation} recommendation generated`,
  });

  return { finalReport, currentStage: 'complete' };
}
